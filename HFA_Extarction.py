def Select_Practice(driver, practice, payer_id, invoice):
    """Select practice reliably, search invoice, and open the claim form."""

    wait = WebDriverWait(driver, WAIT_TIME)
    practice = practice.strip()

    practice_locator = (By.XPATH, "//*[@id='ddlPractice']")

    def normalize(value):
        return re.sub(r"\s+", " ", (value or "").strip()).lower()

    def select_practice_once():
        practice_box = wait.until(
            EC.presence_of_element_located(practice_locator)
        )

        # Scroll into view and open the control so dynamic options can load.
        try:
            driver.execute_script(
                "arguments[0].scrollIntoView({block:'center'});", practice_box
            )
            practice_box.click()
        except Exception:
            pass

        if practice_box.tag_name.lower() != "select":
            practice_box.clear()
            practice_box.send_keys(practice)
            practice_box.send_keys(Keys.ENTER)
            return practice_box

        selector = Select(practice_box)
        wanted = normalize(practice)

        # Match in this order:
        # 1. exact visible text
        # 2. exact option value
        # 3. normalized visible text
        # 4. option text starting with practice
        # 5. option text containing practice, only if unique
        options = selector.options

        for option in options:
            if normalize(option.text) == wanted:
                selector.select_by_value(option.get_attribute("value"))
                return practice_box

        for option in options:
            if normalize(option.get_attribute("value")) == wanted:
                selector.select_by_value(option.get_attribute("value"))
                return practice_box

        for option in options:
            option_text = normalize(option.text)
            if option_text.startswith(wanted):
                selector.select_by_value(option.get_attribute("value"))
                return practice_box

        contains = [
            option for option in options
            if wanted in normalize(option.text)
        ]

        if len(contains) == 1:
            selector.select_by_value(contains[0].get_attribute("value"))
            return practice_box

        visible_options = [
            option.text.strip()
            for option in options
            if option.text.strip()
        ]

        raise RuntimeError(
            f"Practice '{practice}' not currently available. "
            f"Visible options: {visible_options[:30]}"
        )

    last_error = None

    # The Practice dropdown on this site can refresh asynchronously after
    # returning from a claim page. Retry instead of immediately failing the row.
    for attempt in range(1, 6):
        try:
            practice_box = select_practice_once()

            # Verify the selected value/text.
            if practice_box.tag_name.lower() == "select":
                selected = Select(practice_box).first_selected_option.text.strip()
            else:
                selected = (practice_box.get_attribute("value") or "").strip()

            if normalize(selected) == normalize(practice) or \
               normalize(selected).startswith(normalize(practice)):
                print(f"Practice Selected: {practice}")
                break

            raise RuntimeError(
                f"Practice verification failed. Expected '{practice}', "
                f"got '{selected}'"
            )

        except Exception as e:
            last_error = e
            print(
                f"Practice selection attempt {attempt}/5 failed for "
                f"'{practice}': {e}"
            )

            # Re-read the page/control on the next attempt. This is important
            # because the dropdown is rebuilt by the site after each search.
            if attempt < 5:
                try:
                    practice_box = driver.find_element(*practice_locator)
                    driver.execute_script(
                        """
                        arguments[0].scrollIntoView({block:'center'});
                        arguments[0].dispatchEvent(new Event('change',
                            {bubbles:true}));
                        """,
                        practice_box
                    )
                except Exception:
                    pass

                time.sleep(1.5)

    else:
        raise RuntimeError(
            f"Unable to select practice '{practice}' after 5 attempts: "
            f"{last_error}"
        )

    # Search invoice only after practice is confirmed.
    inv_box = wait.until(
        EC.element_to_be_clickable((By.XPATH, "//*[@id='txtInvNum']"))
    )
    inv_box.clear()
    inv_box.send_keys(invoice)
    inv_box.send_keys(Keys.ENTER)
    print(f"Invoice searched: {invoice}")

    cms_label = "//*[@id='ShowCMSLine']/label/span"

    try:
        wait.until(
            EC.presence_of_element_located((By.XPATH, cms_label))
        )
    except TimeoutException:
        print(f"CMS500 not found for invoice {invoice}")
        return False

    main_handle = driver.current_window_handle
    handles_before = set(driver.window_handles)

    # Uncheck Data Stamp only when currently checked.
    try:
        checkbox = driver.find_element(
            By.XPATH, "//*[@id='ShowCMSLine']/input"
        )
        if checkbox.is_selected():
            driver.execute_script("arguments[0].click();", checkbox)
        print("Data Stamp unchecked")
    except Exception as e:
        print(f"Data Stamp checkbox could not be read: {e}")

    # Open claim form.
    claim_control = wait.until(
        EC.element_to_be_clickable((By.XPATH, cms_label))
    )
    try:
        claim_control.click()
    except Exception:
        driver.execute_script("arguments[0].click();", claim_control)

    # Switch only to a genuinely new tab/window.
    try:
        wait.until(
            lambda d: len(set(d.window_handles) - handles_before) > 0
        )
        new_handle = next(
            iter(set(driver.window_handles) - handles_before)
        )
        driver.switch_to.window(new_handle)
        wait.until(
            lambda d: d.execute_script(
                "return document.readyState"
            ) == "complete"
        )
        print("Claim form opened in new tab")
        return True

    except TimeoutException:
        # Some installations open CMS500 in the current tab.
        if driver.current_window_handle == main_handle:
            print("Claim form opened in current tab")
            return True
        raise

def file_is_free(path):
    """True when no other program (Chrome / antivirus) is holding the file."""
    try:
        with open(path, "ab"):
            return True
    except OSError:
        return False


def snapshot(folders):
    files = set()
    for folder in folders:
        if os.path.isdir(folder):
            for name in os.listdir(folder):
                files.add(os.path.join(folder, name))
    return files


def click_save(driver, main_handle, timeout=30):
    """
    Find and click the Save button in the CMS500 popup.
    Looks in the main document and in every iframe, uses a JS click as fallback.
    Returns: "clicked"      -> Save button clicked
             "popup_closed" -> popup is already gone (PDF probably auto-downloaded)
    Raises TimeoutException if the popup stays open but no Save button is found.
    """
    end = time.time() + timeout
    while time.time() < end:
        # Popup already closed by the site / Chrome?
        try:
            if len(driver.window_handles) <= 1:
                return "popup_closed"
            if driver.current_window_handle == main_handle:
                extra = [h for h in driver.window_handles if h != main_handle]
                driver.switch_to.window(extra[-1])
        except Exception:
            try:
                driver.switch_to.window(main_handle)
            except Exception:
                pass
            return "popup_closed"

        try:
            driver.switch_to.default_content()
            frames = driver.find_elements(By.TAG_NAME, "iframe") + \
                     driver.find_elements(By.TAG_NAME, "frame")
            contexts = [None] + list(range(len(frames)))

            for ctx in contexts:
                driver.switch_to.default_content()
                if ctx is not None:
                    driver.switch_to.frame(ctx)

                found = driver.find_elements(By.ID, "save")
                if found:
                    el = found[0]
                    try:
                        el.click()
                    except Exception:
                        driver.execute_script("arguments[0].click();", el)
                    driver.switch_to.default_content()
                    return "clicked"
        except Exception:
            pass          # page is still loading / changing - try again

        time.sleep(1)

    try:
        info = f"url={driver.current_url!r}, title={driver.title!r}"
    except Exception:
        info = "popup not readable"
    raise TimeoutException(f"Save button not found in CMS500 popup ({info})")


def download_claim_form(driver, main_handle, practice, payer_id, invoice, claim_from):
    wait = WebDriverWait(driver, WAIT_TIME)

    practice_path = os.path.join(DOWNLOAD_PATH, safe_name(practice))
    os.makedirs(practice_path, exist_ok=True)

    # Send downloads to the practice folder
    driver.execute_cdp_cmd(
        "Browser.setDownloadBehavior",
        {"behavior": "allow", "downloadPath": practice_path}
    )

    # Watch both the practice folder and the root download folder
    # (Chrome sometimes still saves in the default folder)
    folders = [practice_path, DOWNLOAD_PATH]
    before = snapshot(folders)

    result = click_save(driver, main_handle)
    if result == "clicked":
        print("Save clicked - waiting for PDF...")
    else:
        print("Popup closed by itself - waiting for auto-downloaded PDF...")

    start = time.time()
    retried = False
    new_pdfs = []

    while time.time() - start < DOWNLOAD_TIMEOUT:
        files = snapshot(folders)
        new_files = files - before
        in_progress = any(f.lower().endswith((".crdownload", ".tmp")) for f in new_files)
        new_pdfs = [f for f in new_files if f.lower().endswith(".pdf")]

        if new_pdfs and not in_progress:
            break

        # Nothing started at all -> click Save one more time
        if not new_files and not retried and time.time() - start > RETRY_AFTER:
            try:
                if click_save(driver, main_handle, timeout=5) == "clicked":
                    print("No download started - Save clicked again")
            except Exception as e:
                print(f"Retry click skipped: {e}")
            retried = True

        time.sleep(1)
    else:
        raise TimeoutError(
            f"PDF not downloaded in {DOWNLOAD_TIMEOUT}s. "
            f"New files seen: {[os.path.basename(f) for f in snapshot(folders) - before]}"
        )

    new_file_path = os.path.join(
        practice_path,
        safe_name(f"{payer_id}_{invoice}_{claim_from}") + ".pdf"
    )

    # Wait until the file is fully written AND released by Chrome / antivirus,
    # then rename. Retry because Windows keeps the file locked for a while.
    moved = False
    last_err = None
    old_file = None

    for attempt in range(40):                      # up to ~80 seconds
        candidates = [
            f for f in (snapshot(folders) - before)
            if f.lower().endswith(".pdf")
            and os.path.abspath(f) != os.path.abspath(new_file_path)
        ]
        if candidates:
            old_file = max(candidates, key=os.path.getmtime)
            try:
                if os.path.getsize(old_file) > 0 and file_is_free(old_file):
                    if os.path.exists(new_file_path):
                        os.remove(new_file_path)
                    os.replace(old_file, new_file_path)   # also moves across folders
                    moved = True
                    break
            except OSError as e:
                last_err = e
        time.sleep(2)

    if moved:
        print(f"Claim Form Downloaded ({int(time.time() - start)}s) -> {os.path.basename(new_file_path)}")
    else:
        # Do not lose the download: keep it with a unique name instead of failing the row
        if old_file and os.path.exists(old_file):
            fallback = os.path.join(
                practice_path,
                safe_name(f"{payer_id}_{invoice}_{claim_from}") + f"_{int(time.time())}.pdf"
            )
            try:
                shutil.copy2(old_file, fallback)
                print(f"!! Rename failed ({last_err}); saved copy as {os.path.basename(fallback)}")
            except OSError:
                print(f"!! Rename failed ({last_err}); file left as {old_file}")
        else:
            raise RuntimeError(f"Downloaded PDF not found for rename. Last error: {last_err}")

    # Return cleanly to Receivable.
    # Do not blindly click Back: after closing the popup we may already be
    # on the search page, and clicking Back again causes the return loop.
    if not return_to_receivable(driver, main_handle):
        raise RuntimeError("Could not return to Receivable search page")


