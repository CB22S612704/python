def clean_cell(value):
    """Convert an Excel cell to a clean string (no '123.0', no time part on dates)."""
    if value is None:
        return ""
    if hasattr(value, "strftime"):               # datetime / date cell
        return value.strftime("%m-%d-%Y")
    if isinstance(value, float) and value.is_integer():
        return str(int(value))
    return str(value).strip()


def safe_name(text):
    """Remove characters Windows does not allow in file / folder names."""
    return re.sub(r'[<>:"/\\|?*]', "-", text).strip() or "unknown"


def save_workbook(wb):
    """Save Excel; if the file is open in Excel, warn instead of crashing the run."""
    try:
        wb.save(EXCEL_FILE)
    except PermissionError:
        print("!! Cannot save Excel - close the file in Excel. Status not saved.")


def first_clickable(wait, locators):
    """Return the first element that becomes clickable from a list of locators."""
    return wait.until(EC.any_of(*[EC.element_to_be_clickable(l) for l in locators]))


def first_present(wait, locators):
    return wait.until(EC.any_of(*[EC.presence_of_element_located(l) for l in locators]))


def close_extra_windows(driver, main_handle):
    for handle in list(driver.window_handles):
        if handle != main_handle:
            try:
                driver.switch_to.window(handle)
                driver.close()
            except Exception:
                pass
    driver.switch_to.window(main_handle)


def return_to_receivable(driver, main_handle):
    """Close claim popup and return exactly once to the Receivable search page."""
    wait = WebDriverWait(driver, WAIT_TIME)

    # Close every popup/window except the original Receivable tab.
    close_extra_windows(driver, main_handle)

    # We are already on the search page -> DO NOT click Back again.
    try:
        if driver.find_elements(By.XPATH, "//*[@id='ddlPractice']"):
            return True
    except Exception:
        pass

    # Otherwise go back once and wait for the search controls.
    back_buttons = driver.find_elements(By.XPATH, "//*[@id='btnBack']")
    if back_buttons:
        try:
            wait.until(EC.element_to_be_clickable((By.XPATH, "//*[@id='btnBack']"))).click()
        except Exception:
            driver.execute_script("arguments[0].click();", back_buttons[0])

    try:
        wait.until(EC.presence_of_element_located((By.XPATH, "//*[@id='ddlPractice']")))
        return True
    except TimeoutException:
        return False


