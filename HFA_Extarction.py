def login(driver, username, password, security_key):
    wait = WebDriverWait(driver, WAIT_TIME)

    driver.get(URL)

    # Username
    wait.until(EC.presence_of_element_located((By.ID, "txtLogin"))).send_keys(username)
    wait.until(EC.element_to_be_clickable((By.ID, "btnNext"))).click()

    # Next / verify-with-password button
    first_clickable(wait, [(By.XPATH, "//*[@id='form20']/div[2]/input")] + SUBMIT_BTN).click()

    # Password
    pwd_box = first_present(wait, [
        (By.ID, "input54"),
        (By.CSS_SELECTOR, "input[type='password']"),
    ])
    pwd_box.send_keys(password)
    first_clickable(wait, [(By.XPATH, "//*[@id='form46']/div[2]/input")] + SUBMIT_BTN).click()
    wait.until(EC.staleness_of(pwd_box))          # make sure the password page is gone

    # OTP (generate it now so it is fresh)
    otp_box = first_present(wait, [
        (By.ID, "input80"),
        (By.CSS_SELECTOR, "input[name='credentials.passcode']"),
    ])
    otp = pyotp.TOTP(security_key.replace(" ", "").upper()).now()
    otp_box.send_keys(otp)
    first_clickable(wait, [(By.XPATH, "//*[@id='form72']/div[2]/input")] + SUBMIT_BTN).click()

    print("Login submitted")


