def get_login():
    """Read the Login sheet and return the first valid (username, password, key)."""
    login_df = pd.read_excel(EXCEL_FILE, sheet_name="Login", dtype=str).fillna("")

    for index, row in login_df.iterrows():
        username = row["Username"].strip()
        password = row["Password"].strip()
        security_key = row["Security Key"].strip().replace(" ", "").upper()

        if not username or not security_key:
            print(f"Row {index + 2}: Username or Security Key missing")
            continue

        try:
            pyotp.TOTP(security_key).now()      # validate key only
            return username, password, security_key
        except Exception as e:
            print(f"Row {index + 2}: Invalid Security Key - {e}")

    return None


def main():
    creds = get_login()
    if not creds:
        print("No valid login found")
        return
    username, password, security_key = creds

    driver = start_driver()

    try:
        login(driver, username, password, security_key)
        Patient(driver)

        main_handle = driver.current_window_handle

        # ---- CLAIMFROM SHEET ----
        wb = openpyxl.load_workbook(EXCEL_FILE)
        ws = wb["Claimfrom"]

        for row_index in range(2, ws.max_row + 1):

            practice = clean_cell(ws.cell(row=row_index, column=COL_PRACTICE).value)
            payer_id = clean_cell(ws.cell(row=row_index, column=COL_PAYER_ID).value)
            invoice = clean_cell(ws.cell(row=row_index, column=COL_INVOICE).value)
            claim_form_status = clean_cell(ws.cell(row=row_index, column=COL_STATUS).value)
            claim_from = clean_cell(ws.cell(row=row_index, column=COL_CLAIM_FROM).value)

            if not practice or not invoice:
                continue

            if claim_form_status.lower() == "downloaded":
                continue

            try:
                if Select_Practice(driver, practice, payer_id, invoice):
                    download_claim_form(driver, main_handle, practice,
                                        payer_id, invoice, claim_from)

                    ws.cell(row=row_index, column=COL_STATUS).value = "Downloaded"
                    save_workbook(wb)
                    print(f"Row {row_index}: Downloaded")

                else:
                    ws.cell(row=row_index, column=COL_STATUS).value = "CMS500 Not Found"
                    save_workbook(wb)
                    print(f"Row {row_index}: CMS500 Not Found")

            except Exception as e:
                print(f"Row {row_index}: Download Failed - {e}")
                traceback.print_exc()

                ws.cell(row=row_index, column=COL_STATUS).value = "Failed"
                save_workbook(wb)

                # Recover to the Receivable page without double-clicking Back.
                try:
                    if not return_to_receivable(driver, main_handle):
                        print("!! Could not recover Receivable page; reopening Patient menu")
                        Patient(driver)
                except Exception:
                    traceback.print_exc()

    finally:
        driver.quit()


if __name__ == "__main__":
    main()